export function toPublicCognitiveQuestionsLocalized(
  lang: PipelineLanguage,
): PublicCognitiveQuestion[] {
  return COGNITIVE_QUESTIONS.map(({ correctIndex: _c, ...rest }) => {
    if (lang !== "el") return rest;
    const el = COG_EL[rest.id];
    if (!el) return rest;
    return {
      ...rest,
      prompt: el.prompt,
      options: el.options ?? rest.options,
    };
  });
}

export function toPublicEqScenariosLocalized(lang: PipelineLanguage): {
  id: string;
  prompt: string;
  options: string[];
}[] {
  return EQ_SCENARIOS.map((s) => {
    const el = lang === "el" ? EQ_EL[s.id] : null;
    return {
      id: s.id,
      prompt: el?.prompt ?? s.prompt,
      options: el?.options ?? s.options.map((o) => o.text),
    };
  });
}
